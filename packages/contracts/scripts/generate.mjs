import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const schemaDir = join(root, "schema");
const schemas = readdirSync(schemaDir)
  .filter((name) => name.endsWith(".schema.json"))
  .sort()
  .map((name) => join(schemaDir, name));

// Every property must be listed in `required`. A value that can be missing is
// nullable instead of optional, because quicktype's Dart output serializes an
// absent optional property as null, which the schema would then reject.
function optionalProperties(node, path) {
  if (Array.isArray(node)) return node.flatMap((child, i) => optionalProperties(child, `${path}/${i}`));
  if (node === null || typeof node !== "object") return [];
  const own = node.properties
    ? Object.keys(node.properties)
        .filter((key) => !(node.required ?? []).includes(key))
        .map((key) => `${path}/properties/${key}`)
    : [];
  return own.concat(
    Object.entries(node).flatMap(([key, child]) => optionalProperties(child, `${path}/${key}`)),
  );
}

const optional = schemas.flatMap((file) =>
  optionalProperties(JSON.parse(readFileSync(file, "utf8")), file.slice(root.length + 1)),
);
if (optional.length > 0) {
  console.error(
    `Optional properties are not allowed; make them required and nullable:\n  ${optional.join("\n  ")}`,
  );
  process.exit(1);
}

const header =
  "// Generated by packages/contracts/scripts/generate.mjs from packages/contracts/schema.\n" +
  "// Do not edit. Run `pnpm --filter @fieldnote/contracts generate`.\n\n";

const targets = [
  {
    path: join(root, "generated", "ts", "index.ts"),
    args: ["--lang", "ts", "--just-types", "--prefer-const-values"],
  },
  {
    path: join(root, "dart", "lib", "fieldnote_contracts.dart"),
    args: ["--lang", "dart"],
  },
];

function render(target) {
  const dir = mkdtempSync(join(tmpdir(), "contracts-"));
  try {
    const out = join(dir, "out");
    execFileSync(
      join(root, "node_modules", ".bin", "quicktype"),
      ["--src-lang", "schema", ...target.args, "--out", out, ...schemas],
      { stdio: ["ignore", "ignore", "inherit"] },
    );
    return header + readFileSync(out, "utf8");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const check = process.argv.includes("--check");
const stale = [];
for (const target of targets) {
  const expected = render(target);
  if (check) {
    let actual = "";
    try {
      actual = readFileSync(target.path, "utf8");
    } catch {}
    if (actual !== expected) stale.push(target.path);
  } else {
    writeFileSync(target.path, expected);
  }
}

if (stale.length > 0) {
  console.error(
    `Generated contracts are out of date:\n  ${stale.join("\n  ")}\n` +
      "Run `pnpm --filter @fieldnote/contracts generate` and commit the result.",
  );
  process.exit(1);
}
console.log(check ? "Generated contracts are up to date." : "Generated contracts written.");
